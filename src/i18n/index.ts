// 取当前语言下的文案（支持 {n} 占位符替换）
export function t(key: string, vars?: Record<string, string | number>): string {
  const entry = (UI_DICT as Record<string, { zh: string; en: string }>)[key];
  if (!entry) return key;
  const lang = useRelationshipStore.getState().language;
  let text = lang === 'en' ? entry.en : entry.zh;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return text;
}

// React Hook：订阅 language 变化，用于组件重渲染
export function useLang(): Language {
  return useRelationshipStore((s) => s.language);
}

// 语言对应的语音合成 code
export function speechLang(lang: Language): string {
  return lang === 'en' ? 'en-US' : 'zh-CN';
}

